-- VERT core schema: accounts, devices, zones, rules, alerts, reminders.

create extension if not exists "uuid-ossp";

create table users (
    id uuid primary key default uuid_generate_v4(),
    email text unique not null,
    password_hash text not null,
    display_name text not null,
    locale text not null default 'en',
    role text not null default 'operator', -- 'admin' | 'operator' | 'viewer'
    -- Bumped to end every session (password change/reset, access removed);
    -- session tokens carry it as "tv". Existing databases get these two
    -- columns from the gateway at startup (store.EnsureSchema).
    token_version int not null default 0,
    disabled boolean not null default false, -- access removed by an admin (reversible)
    created_at timestamptz not null default now()
);

create table zones (
    id uuid primary key default uuid_generate_v4(),
    name text not null,
    created_at timestamptz not null default now()
);

create table devices (
    id text primary key,              -- device_id, e.g. "dht22-01"
    device_type text not null,        -- e.g. "temp-humidity", "camera"
    zone_id uuid references zones(id),
    capabilities jsonb not null,       -- capability descriptor announced at registration
    display_name text,
    last_seen_at timestamptz,
    status text not null default 'offline', -- 'online' | 'offline'
    last_reading jsonb,                -- most recent telemetry payload, e.g. {"temp_c": 23.4} or an AI health result
    local_ip text,                     -- reported at announce time; how the dashboard reaches a camera's own live-view stream directly (bypassing the broker, which isn't built for video)
    created_at timestamptz not null default now()
);

-- Per-device machine credentials, issued once at provisioning time and
-- never shown again. Devices use device_id as their MQTT username /
-- HTTP Basic Auth username, and this secret as the matching password.
-- Hashed with SHA-256 (not bcrypt): device secrets are already
-- high-entropy random tokens generated by us, not human passwords, so a
-- fast constant-time comparison is the right tool -- RabbitMQ calls the
-- gateway's auth webhook on every device connection, and a slow hash
-- there would make every sensor's reconnect noticeably sluggish.
create table device_credentials (
    device_id text primary key references devices(id) on delete cascade,
    secret_hash text not null,
    issued_at timestamptz not null default now(),
    issued_by uuid references users(id),
    revoked_at timestamptz
);

create table automation_rules (
    id uuid primary key default uuid_generate_v4(),
    zone_id uuid references zones(id),        -- rule applies to every device in this zone...
    device_id text references devices(id),    -- ...or, if set, to just this one device
    name text not null,
    condition jsonb not null,   -- e.g. {"metric": "temp_c", "op": ">", "value": 40, "for_minutes": 10}
    action jsonb not null,      -- e.g. {"device_id": "window01", "command": "open"}
    enabled boolean not null default true,
    created_at timestamptz not null default now()
);

create table alerts (
    id uuid primary key default uuid_generate_v4(),
    device_id text references devices(id),
    rule_id uuid references automation_rules(id),
    severity text not null default 'warning', -- 'info' | 'warning' | 'critical'
    message text not null,
    acknowledged boolean not null default false,
    created_at timestamptz not null default now()
);

create table reminders (
    id uuid primary key default uuid_generate_v4(),
    user_id uuid references users(id),
    title text not null,
    description text,
    due_at timestamptz not null,
    recurrence text,           -- null | 'daily' | 'weekly' | 'biweekly' | cron expression
    completed boolean not null default false,
    created_at timestamptz not null default now()
);

-- One row per image uploaded by a camera device, so the dashboard (or a
-- worried grower checking in from their phone) can list and re-view past
-- frames, not just react to the live MQTT event.
create table frames (
    id uuid primary key default uuid_generate_v4(),
    device_id text not null references devices(id) on delete cascade,
    object_key text not null,   -- key inside the MinIO/S3 bucket
    content_type text not null default 'image/jpeg',
    size_bytes bigint not null,
    created_at timestamptz not null default now()
);
create index frames_device_id_created_at_idx on frames (device_id, created_at desc);

create table dashboards (
    id uuid primary key default uuid_generate_v4(),
    user_id uuid references users(id),
    name text not null,
    layout jsonb not null,
    created_at timestamptz not null default now()
);
